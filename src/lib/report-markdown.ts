import { computeHealthScore } from "@/lib/scoring";
import { CATEGORY_LABELS, PRIORITY_WEIGHTS, type InspectionReport } from "@/lib/types";

const RUN_LABEL = { initial: "Initial inspection", retest_failed: "Retest (failed tests)", retest_all: "Retest (all tests)" } as const;

export function reportToMarkdown(report: InspectionReport): string {
  const { inspection, runs, tests } = report;
  const latest = tests.map((t) => t.results.at(-1));
  const score = computeHealthScore(tests.map((t, i) => ({ priority: t.priority, status: latest[i]?.execution_status ?? "NOT_EXECUTED" })));
  const lines: string[] = [];
  lines.push(`# CECH Inspection Report`);
  lines.push("");
  lines.push(`- **Website:** ${inspection.website_url}`);
  lines.push(`- **Inspection ID:** ${inspection.id}`);
  lines.push(`- **Created:** ${inspection.created_at}`);
  lines.push(`- **Completed:** ${inspection.completed_at ?? "in progress"}`);
  lines.push(`- **Overall status:** ${inspection.overall_status.toUpperCase()}`);
  lines.push(
    `- **Health score:** ${score.score != null ? `${score.score}/100` : `Insufficient data (${score.reason})`} — weighted pass rate over conclusive Kane verdicts (high=3, medium=2, low=1). Not a guarantee of correctness or security.`,
  );
  lines.push(`- **Test plan source:** ${inspection.plan_source === "groq" ? "Groq AI" : "CECH baseline (Groq unavailable)"}`);
  lines.push("");

  if (inspection.summary) {
    lines.push(`## Summary`, "", `**${inspection.summary.headline}**`, "", inspection.summary.overview, "");
    if (inspection.summary.key_issues.length) lines.push("**Key issues**", ...inspection.summary.key_issues.map((i) => `- ${i}`), "");
    if (inspection.summary.next_steps.length) lines.push("**Next steps**", ...inspection.summary.next_steps.map((i) => `- ${i}`), "");
  }

  lines.push(`## Verification runs`, "", `| # | Type | Status | Passed | Failed | Inconclusive | Errors | Score |`, `|---|---|---|---|---|---|---|---|`);
  for (const r of runs) {
    lines.push(
      `| ${r.sequence} | ${RUN_LABEL[r.run_type]} | ${r.status} | ${r.passed} | ${r.failed} | ${r.inconclusive} | ${r.errored} | ${r.health_score ?? "—"} |`,
    );
  }
  lines.push("");

  lines.push(`## Tests`, "");
  for (const t of tests) {
    lines.push(`### ${t.title}`);
    lines.push(`- Category: ${CATEGORY_LABELS[t.category]} · Priority: ${t.priority} (weight ${PRIORITY_WEIGHTS[t.priority]})`);
    lines.push(`- Expected: ${t.expected_outcome}`);
    if (t.assumption) lines.push(`- Assumption: ${t.assumption}`);
    for (const res of t.results) {
      const run = runs.find((r) => r.id === res.verification_run_id);
      lines.push("");
      lines.push(`**Run ${run?.sequence ?? "?"} — browser outcome: ${res.execution_status}**${res.error_kind ? ` (${res.error_kind})` : ""}`);
      lines.push(`- Objective executed by Kane: ${res.objective}`);
      if (res.objective_note) lines.push(`- Objective note: ${res.objective_note}`);
      if (res.duration_ms != null) lines.push(`- Duration: ${(res.duration_ms / 1000).toFixed(1)}s`);
      if (res.kane_summary) lines.push(`- Kane summary: ${res.kane_summary}`);
      if (res.kane_reason) lines.push(`- Kane reason: ${res.kane_reason}`);
      if (res.evidence_reference) lines.push(`- Evidence: ${res.evidence_reference}`);
      const a = res.analysis;
      if (a) {
        lines.push(`- AI interpretation (${a.source}): ${a.summary}`);
        if (a.observed_behavior) lines.push(`  - Observed: ${a.observed_behavior}`);
        if (a.expected_behavior) lines.push(`  - Expected: ${a.expected_behavior}`);
        if (a.recommendation) lines.push(`  - Recommendation: ${a.recommendation}`);
        if (a.severity) lines.push(`  - Severity: ${a.severity} · Confidence: ${a.confidence ?? "n/a"}`);
      }
    }
    lines.push("");
  }
  lines.push("---", "Generated by CECH — Don't just launch. Prove it works.");
  return lines.join("\n");
}
