"use client";
import { AlertTriangle, Bug, Eye, Lightbulb, RotateCcw, Wrench } from "lucide-react";
import { Badge } from "@/components/ui/badge";
import type { BugReport } from "@/lib/types";

/** Evidence-grounded reproduction report. Facts, hypotheses and suggestions are kept visibly separate. */
export function BugReportPanel({ report }: { report: BugReport }) {
  return (
    <section className="rounded-3xl border border-border p-5" aria-label="Bug reproduction report">
      <div className="flex flex-wrap items-start justify-between gap-3">
        <div className="min-w-0">
          <p className="flex items-center gap-2 text-xs font-medium text-subtle">
            <Bug className="size-4" /> Bug reproduction report · AI-generated by Groq from captured evidence
          </p>
          <h4 className="mt-1.5 text-[15px] font-semibold leading-snug">{report.title}</h4>
          <p className="mt-1 text-xs text-muted">Affected feature: {report.feature}</p>
        </div>
        <Badge tone={report.severity === "critical" || report.severity === "high" ? "red" : report.severity === "medium" ? "yellow" : "grey"}>{report.severity} severity</Badge>
      </div>

      {!report.evidence_sufficient && (
        <p className="mt-4 flex items-start gap-2 rounded-2xl bg-warning-soft px-3 py-2.5 text-xs text-warning">
          <AlertTriangle className="mt-0.5 size-3.5 shrink-0" /> The captured evidence is not sufficient to explain this failure with confidence. Treat the hypothesis below as a starting point only.
        </p>
      )}

      <p className="mt-4 text-sm leading-relaxed text-foreground/90">{report.description}</p>

      <div className="mt-4 grid gap-4 md:grid-cols-2">
        <div>
          <p className="text-[11px] font-medium uppercase tracking-wider text-subtle">Expected</p>
          <p className="mt-1 text-sm">{report.expected_behavior}</p>
        </div>
        <div>
          <p className="text-[11px] font-medium uppercase tracking-wider text-subtle">Actual</p>
          <p className="mt-1 text-sm">{report.actual_behavior}</p>
        </div>
      </div>

      <div className="mt-5">
        <p className="text-[11px] font-medium uppercase tracking-wider text-subtle">Steps to reproduce</p>
        <ol className="mt-2 list-decimal space-y-1 pl-5 text-sm">
          {report.steps_to_reproduce.map((s, i) => (
            <li key={i}>{s}</li>
          ))}
        </ol>
      </div>

      <div className="mt-5 grid gap-3 lg:grid-cols-3">
        <div className="rounded-2xl bg-surface-2 p-4">
          <p className="flex items-center gap-1.5 text-xs font-semibold">
            <Eye className="size-3.5" /> Observed facts
          </p>
          {report.observed_facts.length ? (
            <ul className="mt-2 space-y-1.5 text-xs leading-relaxed">
              {report.observed_facts.map((f, i) => (
                <li key={i}>{f}</li>
              ))}
            </ul>
          ) : (
            <p className="mt-2 text-xs text-muted">No facts could be tied to captured evidence.</p>
          )}
        </div>
        <div className="rounded-2xl bg-surface-2 p-4">
          <p className="flex items-center gap-1.5 text-xs font-semibold">
            <Lightbulb className="size-3.5" /> Hypothesis <span className="font-normal text-subtle">(unconfirmed)</span>
          </p>
          <p className="mt-2 text-xs leading-relaxed text-muted">{report.hypothesis || "Not enough evidence to form a hypothesis."}</p>
        </div>
        <div className="rounded-2xl bg-surface-2 p-4">
          <p className="flex items-center gap-1.5 text-xs font-semibold">
            <Wrench className="size-3.5" /> Suggested correction
          </p>
          <p className="mt-2 text-xs leading-relaxed">{report.recommendation}</p>
        </div>
      </div>

      <div className="mt-4 rounded-2xl bg-surface-2 p-4">
        <p className="flex items-center gap-1.5 text-xs font-semibold">
          <RotateCcw className="size-3.5" /> Retest objective
        </p>
        <p className="mt-1.5 font-mono text-xs text-muted">{report.retest_objective}</p>
      </div>

      {report.removed_claims.length > 0 && (
        <details className="mt-3 text-xs text-subtle">
          <summary className="cursor-pointer">CECH removed {report.removed_claims.length} unsupported claim{report.removed_claims.length === 1 ? "" : "s"}</summary>
          <ul className="mt-2 space-y-1">
            {report.removed_claims.map((c, i) => (
              <li key={i}>· {c}</li>
            ))}
          </ul>
        </details>
      )}
    </section>
  );
}
